def _promote_flat_keys(args: dict) -> None:
    """Lift flat top-level keys into args['fields'], applying alias mapping.

    Flat keys don't overwrite keys already present in an explicit fields dict
    (old-format payloads win on conflict — backwards compatible).
    Underscore-prefixed and reserved keys are left in place for existing handlers.
    """
    fields = args.get("fields", {})
    for k, v in list(args.items()):
        if k in _RESERVED_TOP or k.startswith("_"):
            continue
        canonical = ALIASES.get(k.lower(), k)
        if canonical not in fields:
            fields[canonical] = v
    args["fields"] = fields


def _normalize_field_names(htype: str, fields: dict) -> None:
    """Rename mis-cased field keys to their canonical form in-place."""
    order = _get_field_order(htype)
    canonical_map = {f.lower(): f for f in order}
    for k in list(fields):
        lk = k.lower()
        if lk in canonical_map and canonical_map[lk] != k:
            fields[canonical_map[lk]] = fields.pop(k)


def _apply_field_defaults(htype: str, fields: dict, key: str) -> None:
    """Fill in auto-derived and N/A defaults for any declared field not supplied."""
    fields.setdefault("Ticket", key)
    # Normalize Ticket: strip AC suffix if model passed full ID (e.g. "LOC-0031-AC1" → "LOC-0031")
    ticket = fields.get("Ticket", "")
    _t_match = re.match(r"^(.+)-AC\d+$", ticket)
    if _t_match:
        fields["Ticket"] = _t_match.group(1)
    fields.setdefault("Saved", str(date.today()))
    fields.setdefault("Environment", "N/A")
    fields.setdefault("Mode", "N/A")
    for field_name in _get_field_order(htype):
        fields.setdefault(field_name, "N/A")


