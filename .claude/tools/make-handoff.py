def _get_field_order(htype: str) -> list:
    """Return the ordered field list for a handoff type."""
    if htype in STANDALONE_FIELD_ORDER:
        return STANDALONE_FIELD_ORDER[htype]
    return STANDARD_ORDER + SKILL_FIELDS.get(htype, [])


def _enforce_required_fields(htype: str, fields: dict) -> None:
    """Enforce only the fields the script cannot default — those carrying real session state.

    All other declared fields are filled with N/A by _apply_field_defaults before
    this runs. Only fields in _TRULY_REQUIRED need to be present and carry a real
    value: empty AND "N/A" both count as missing (N/A is a default, not state).
    Underscore-prefixed special fields are structural containers and remain optional.
    """
    required = list(_TRULY_REQUIRED.get("_base", []))
    required += _TRULY_REQUIRED.get(htype, [])
    # Standalone types have no standard block; skip base required for them.
    if htype in STANDALONE_FIELD_ORDER:
        required = _TRULY_REQUIRED.get(htype, [])
    # Repo-intelligence types have no ticket; remove ticket-specific base requirements.
    if htype in {"luke"}:
        required = [f for f in required if f != "Ticket Status"]
    # "Route To" and "Ticket Status" are legitimately N/A (no next skill; local
    # tickets without Jira) — every other truly-required field must carry real state.
    na_exempt = {"Route To", "Ticket Status"}
    def _is_missing(v):
        return not v or str(v).strip().upper() == "N/A"
    missing = [f for f in required
               if f not in na_exempt and _is_missing(fields.get(f))]
    if missing:
        raise UsageError(
            f"'{htype}' handoff is missing required session fields: "
            + ", ".join(f"missing: {f}" for f in missing),
            "these fields cannot be defaulted — they carry real session state; add them to the JSON payload",
        )


# Phrases that indicate the model pointed at Jira instead of writing the actual
# Gherkin inline. Bruce (and any other downstream reader) must get the AC text
# in the handoff itself — a pointer means they have to go fetch the ticket.
_AC_POINTER_PATTERNS = [
    "see the jira ticket", "see jira", "in the jira ticket", "in the ticket description",
    "refer to jira", "refer to the ticket", "full gherkin scenarios are in the jira ticket",
    "expand blocks", "check jira for", "jira has the full",
]


def _enforce_alfred_gherkin(fields: dict) -> None:
    """Alfred must hand Bruce/Damian the actual Gherkin, not a pointer back to Jira.

    Only applies when routing to bruce or damian — the two skills that
    implement/test directly against the AC. Routes to lucius (pre-design,
    ACs not finalized) or dupin (epic-level story breakout, per-story
    handoffs carry their own AC) are exempt.

    Checks the '_blocks.Acceptance Criteria' content (or the flat 'Acceptance
    Criteria' field, since models sometimes put it top-level) for a real
    Given/When/Then body. A handoff that only summarizes AC titles and tells
    the reader to go look at Jira defeats the purpose of the handoff.
    """
    route_to = str(fields.get("Route To", "")).strip().lower()
    if route_to not in {"bruce", "damian"}:
        return

    blocks = fields.get("_blocks") or {}
    ac_text = blocks.get("Acceptance Criteria") or fields.get("Acceptance Criteria") or ""
    if not isinstance(ac_text, str):
        ac_text = str(ac_text)
    lower = ac_text.lower()

    if not ac_text.strip():
        raise UsageError(
            "'alfred' handoff is missing '_blocks.Acceptance Criteria' — the full "
            "refined Gherkin must be written into the handoff, not left for the reader to fetch from Jira",
            "write the full Given/When/Then scenarios into _blocks['Acceptance Criteria']",
        )

    for pattern in _AC_POINTER_PATTERNS:
        if pattern in lower:
            raise UsageError(
                f"'alfred' handoff's Acceptance Criteria contains a Jira pointer phrase "
                f"('{pattern}') instead of the actual Gherkin",
                "write the full Given/When/Then scenarios inline in the handoff",
            )

    if "given" not in lower or "when" not in lower or "then" not in lower:
        raise UsageError(
            "'alfred' handoff's Acceptance Criteria has no Given/When/Then content",
            "write the full refined Gherkin scenarios into the handoff so Bruce/Damian don't have to open the Jira ticket",
        )


def _make_table(rows: list[dict]) -> str:
    """Build a markdown table from a list of row dicts."""
    if not rows:
        return ""
    cols = list(rows[0].keys())
    lines = []
    lines.append("| " + " | ".join(cols) + " |")
    lines.append("| " + " | ".join("---" for _ in cols) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(c, "")) for c in cols) + " |")
    return "\n".join(lines)




def build_handoff(htype: str, key: str, fields: dict) -> str:
    """Build the markdown content for a handoff file."""
    header = fields.pop("_header", HEADERS.get(htype, f"## {htype} Handoff"))
    header = header.replace("{key}", key)
    tables = fields.pop("_tables", {})
    blocks = fields.pop("_blocks", {})
    fields.pop("_delete_on_success", None)  # handled by caller
    chain = fields.pop("_chain", [])
    context = fields.pop("_context", {})
    conversation_context = fields.pop("_conversation_context", {})
    raw_context = fields.pop("_raw", "")
    ac_id = fields.pop("_ac_id", None)
    depends_on = fields.pop("_depends_on", [])
    fields.pop("_files_map", None)  # deprecated — flat files_changed field used instead
    agent_id = fields.pop("_agent_id", None)
    parent = fields.pop("_parent", None)
    started_at = fields.pop("_started_at", None)
    patch_path = fields.pop("_patch", None)
    queue_entry = fields.pop("_queue_entry", None)
    open_questions = fields.pop("_open_questions", [])
    resume_instructions = fields.pop("_resume_instructions", "")
    conversation_export = fields.pop("_conversation_export", "")

    lines = [header]

    # Pipeline position banner — receiving skill sees sender + intent first
    sender = PIPELINE_NAMES.get(htype)
    route_to = fields.get("Route To", "")
    if sender and htype not in STANDALONE_FIELD_ORDER:
        if route_to:
            lines.append(f"**Gotham Pipeline** · {sender} → {route_to}")
        else:
            lines.append(f"**Gotham Pipeline** · {sender}")

    # Auto-insert grep-friendly completion stamp when Status is a completion
    # value. 'complete' is canonical, but models may write 'done'/'passed'/
    # 'success' — normalize all of them so downstream scanners (find_handoff,
    # validate_handoff_chain) never treat a finished handoff as missing.
    COMPLETE_STATUSES = {"complete", "done", "passed", "pass", "success"}
    if fields.get("Status", "").lower() in COMPLETE_STATUSES:
        lines.append("status: complete")

    # Ordered fields first
    order = _get_field_order(htype)
    written = set()

    for field_name in order:
        if field_name in fields:
            lines.append(f"**{field_name}:** {fields[field_name]}")
            written.add(field_name)

    # Remaining fields (not in order list, not special)
    for field_name, value in fields.items():
        if field_name not in written:
            lines.append(f"**{field_name}:** {value}")

    # V2 fields — agent identity, chain, context, AC tracking, file map
    if agent_id:
        lines.append(f"**Agent:** {agent_id}")
    if parent:
        lines.append(f"**Parent:** {parent}")
    if started_at:
        lines.append(f"**Started At:** {started_at}")
    if patch_path:
        lines.append(f"**Patch:** {patch_path}")
    if queue_entry:
        lines.append(f"**Queue Entry:** {queue_entry}")
    if ac_id:
        if isinstance(ac_id, list):
            lines.append(f"**AC:** {', '.join(ac_id)}")
        else:
            lines.append(f"**AC:** {ac_id}")
    if depends_on:
        lines.append(f"**Depends On:** {', '.join(depends_on)}")
    if chain:
        lines.append("")
        lines.append("**Chain:**")
        for link in chain:
            lines.append(f"- `{link}`")
    if context:
        lines.append("")
        lines.append("**Context:**")
        for ctx_key, ctx_val in context.items():
            if isinstance(ctx_val, list):
                lines.append(f"- **{ctx_key}:** {'; '.join(ctx_val)}")
            elif isinstance(ctx_val, dict):
                items = [f"{k}: {v}" for k, v in ctx_val.items()]
                lines.append(f"- **{ctx_key}:** {'; '.join(items)}")
            else:
                lines.append(f"- **{ctx_key}:** {ctx_val}")
    # Conversation context — structured context for standalone agent operation
    CONV_CTX_FIELDS = [
        "user_intent", "decisions_and_reasoning", "rejected_approaches",
        "user_decisions", "domain_knowledge", "priority", "whats_been_explained",
    ]
    CONV_CTX_LABELS = {
        "user_intent": "User intent",
        "decisions_and_reasoning": "Decisions and reasoning",
        "rejected_approaches": "Rejected approaches",
        "user_decisions": "User decisions",
        "domain_knowledge": "Domain knowledge",
        "priority": "Priority",
        "whats_been_explained": "What's been explained",
    }
    if conversation_context:
        lines.append("")
        lines.append("**Conversation Context:**")
        for field in CONV_CTX_FIELDS:
            val = conversation_context.get(field)
            if val:
                lines.append(f"- **{CONV_CTX_LABELS[field]}:** {val}")
        # Any extra keys not in the standard set
        for k, v in conversation_context.items():
            if k not in CONV_CTX_FIELDS and v:
                lines.append(f"- **{k}:** {v}")

    # Raw context dump — freeform content for standalone agents
    if raw_context:
        lines.append("")
        lines.append("**Raw Context:**")
        lines.append(raw_context)

    # Open questions — structured blockers for next phase
    if open_questions:
        lines.append("")
        lines.append("**Open Questions:**")
        lines.append(_make_table(open_questions))

    # Resume instructions — explicit next-action for resuming agent
    if resume_instructions:
        lines.append("")
        lines.append(f"**Resume Instructions:** {resume_instructions}")

    # Conversation export — pointer to full transcript
    if conversation_export:
        lines.append(f"**Conversation Export:** {conversation_export}")

    # Tables
    for section_name, rows in tables.items():
        lines.append("")
        lines.append(f"**{section_name}:**")
        lines.append(_make_table(rows))

    # Text blocks
    for section_name, content in blocks.items():
        lines.append("")
        lines.append(f"**{section_name}:**")
        if isinstance(content, list):
            if content and all(isinstance(r, dict) for r in content):
                lines.append(_make_table(content))
            else:
                for item in content:
                    lines.append(str(item))
        elif isinstance(content, dict):
            for k, v in content.items():
                lines.append(f"- **{k}:** {v}")
        else:
            lines.append(content)

    return "\n".join(lines) + "\n"


def _strip_surrogates(obj):
    """Recursively strip lone surrogate characters from all string values."""
    if isinstance(obj, str):
        return obj.encode("utf-8", errors="replace").decode("utf-8")
    if isinstance(obj, dict):
        return {k: _strip_surrogates(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_strip_surrogates(v) for v in obj]
    return obj


def handle(v):
    raw = v["--json"]
    if raw == "-":
        raw = sys.stdin.read().strip()
    if not raw:
        raise UsageError(
            "empty JSON payload",
            "pipe the payload via stdin: $UB make-handoff --json - <<'HANDOFF' ... HANDOFF",
        )
    try:
        args = json.loads(raw)
    except json.JSONDecodeError as e:
        raise UsageError(f"invalid JSON payload: {e}", "fix the JSON and re-run")
    if not isinstance(args, dict):
        raise UsageError(
            "JSON payload must be an object",
            "use {\"type\": ..., \"ticket_key\": ..., \"fields\": {...}}",
        )

    base = Path(args.get("base_dir") or v["--base"])
    htype = args.get("type")
    key = args.get("ticket_key")
    if not htype:
        raise UsageError("'type' is required in the JSON payload", "add \"type\": \"<handoff type>\"")
    if not key:
        raise UsageError("'ticket_key' is required in the JSON payload", "add \"ticket_key\": \"<KEY>\"")

    # --- Flat interface: lift top-level keys into fields, apply aliases + defaults ---
    _promote_flat_keys(args)
    fields = args.get("fields", {})

    # Rescue special keys placed at top level instead of inside fields.
    # Models frequently put _blocks, _tables, _context etc. as siblings of
    # "type"/"ticket_key" rather than nested in "fields". Merge them in so
    # build_handoff sees them regardless of where the model placed them.
    _SPECIAL = {
        "_blocks", "_tables", "_header", "_delete_on_success", "_chain",
        "_context", "_conversation_context", "_raw", "_ac_id", "_depends_on",
        "_files_map", "_agent_id", "_parent", "_started_at",
        "_patch", "_queue_entry", "_open_questions", "_resume_instructions",
        "_conversation_export",
    }
    for sk in _SPECIAL:
        if sk in args and sk not in fields:
            fields[sk] = args[sk]

    if htype not in HANDOFF_PATHS:
        raise UsageError(
            f"unknown handoff type: {htype}. Valid: {', '.join(HANDOFF_PATHS.keys())}",
            "use one of the valid handoff types listed in the error",
        )

    # Dupin epic/phase state is per-EPIC — never per-AC. An AC-suffixed key here
    # produced top-level handoffs/dupin/<STORY>-AC<n>.md files the scanner doesn't
    # read; per-AC state belongs in the dup-* stage files.
    if htype in ("dupin", "phase-state") and re.search(r"-AC\d+$", key):
        raise UsageError(
            f"'{htype}' is epic/phase state — key {key!r} has an AC suffix",
            "use the dup-* stage types for stage handoffs (they write handoffs/dupin/<STORY>/<stage>-<STORY>.md)",
        )

    _normalize_field_names(htype, fields)
    _apply_field_defaults(htype, fields, key)
    _enforce_required_fields(htype, fields)
    if htype == "alfred":
        _enforce_alfred_gherkin(fields)

    folder, filename_template = HANDOFF_PATHS[htype]
    out_dir = base / folder
    out_dir.mkdir(parents=True, exist_ok=True)

    se_status = "skipped"

    if htype == "session":
        completed_dir = out_dir / "completed"
        completed_dir.mkdir(parents=True, exist_ok=True)
        for old in out_dir.glob("Session-*.md"):
            old.replace(completed_dir / old.name)

    if htype in _DUPIN_TYPES:
        # ac_selected is aliased to "A/C Selected (this session)" by _promote_flat_keys
        ac_selected = fields.get("A/C Selected (this session)", "")
        # Strip AC suffix from key if present (e.g. "LOC-0035-AC2" → "LOC-0035")
        _key_strip = re.match(r"^(.+)-AC\d+$", key)
        story_key = _key_strip.group(1) if _key_strip else key
        if re.search(r"-AC\d+$", story_key):
            # Doubled per-AC dir (handoffs/dupin/<STORY>-AC<n>/<stage>-<STORY>-AC<n>-AC<n>.md)
            # is scanner-invisible. The story key itself must not carry an AC suffix.
            raise UsageError(
                f"story key {story_key!r} still carries an AC suffix",
                "pass ticket_key as <STORY> or <STORY>/AC<n> so the file lands in handoffs/dupin/<STORY>/",
            )
        # Extract unit from ac_selected (story key, legacy per-AC key, or "pr-<STORY>" for PRs)
        if htype == "dup-pr" and ac_selected.startswith("pr-"):
            ac_id_for_path = ac_selected
        elif "/" in key:
            _, ac_id_for_path = key.rsplit("/", 1)
        else:
            _ac_extract = re.search(r"(AC\d+)", ac_selected)
            ac_id_for_path = _ac_extract.group(1) if _ac_extract else ac_selected
        # build_ac_handoff_path appends "handoffs/dupin/<story>" itself, so the
        # base must be BASE_DIR (~/.claude) — passing out_dir.parent produced a
        # nested handoffs/handoffs/dupin/ tree the scanner never reads.
        # Story-level dispatch (dupin plan §3.3): ac_selected carries a bare
        # story key (no AC suffix) → deterministic story handoff path
        # {stage}-{STORY}.md. Everything else keeps the legacy per-AC path.
        if htype != "dup-pr" and re.fullmatch(r"[A-Z][A-Z0-9]*-\d{3,4}", ac_id_for_path):
            out_path = build_story_handoff_path(base, htype, story_key)
        else:
            out_path = build_ac_handoff_path(base, htype, story_key, ac_id_for_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        fields = _strip_surrogates(fields)
        content = build_handoff(htype, key, dict(fields))
        out_path.write_text(content, encoding="utf-8")
        _post_write(base, htype, key, str(out_path),
                    agent_id=fields.get("_agent_id"))
        return {
            "status": "written",
            "type": htype,
            "ticket": key,
            "path": str(out_path),
            "self_evolution": se_status,
        }

    base_filename = filename_template.replace("{key}", key).replace("{ac_id}", key.split("/")[-1] if "/" in key else key)

    out_path = out_dir / base_filename

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fields = _strip_surrogates(fields)
    content = build_handoff(htype, key, dict(fields))  # copy to avoid mutation
    out_path.write_text(content, encoding="utf-8")

    # Delete files on success (e.g. notes file superseded by full handoff)
    # Guard: never delete the file we just wrote
    for del_path in args.get("fields", {}).get("_delete_on_success", []):
        p = Path(del_path).resolve()
        if p == out_path.resolve():
            continue
        if p.exists():
            p.unlink()

    # Audit post-write
    _post_write(base, htype, key, str(out_path))

    # Self-evolution check — runs inline after handoff write
    se_items = args.get("self_evolution")
    if se_items is not None:
        se_status = _run_self_evolution(se_items)

    return {
        "status": "written",
        "type": htype,
        "ticket": key,
        "path": str(out_path),
        "self_evolution": se_status,
    }


